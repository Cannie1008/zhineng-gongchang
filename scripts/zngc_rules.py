def local_rules_for(company):
    """按企业所在城市、省份匹配地方规则（城市优先，可同时命中省和市）。"""
    prov = str((company or {}).get("province") or "")
    city = str((company or {}).get("city") or "")
    out = []
    for r in LOCAL_RULES:
        hay = city if r.get("scope") == "city" else prov
        if r.get("scope") == "city" and not hay:
            hay = prov  # 有人把“青岛”填在省份栏
        if any(m in hay for m in r["match"]):
            out.append(r)
    return out
